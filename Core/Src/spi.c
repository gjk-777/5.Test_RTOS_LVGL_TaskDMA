/*
 * @brief       往SPI发送一个字节，同时接收一个字节
 * @param       txbyte  : 要发送的字节
 * @retval      rxbyte  : 接收到的字节
 */
uint8_t spi_read_write_byte(uint8_t txbyte)
{
  uint8_t rxbyte;
  HAL_SPI_TransmitReceive(&hspi1, &txbyte, &rxbyte, 1, 1000);
  return rxbyte;
}

void spi_set_speed(uint8_t speed)
{
  assert_param(IS_SPI_BAUDRATE_PRESCALER(speed)); /* 检查参数是否有效 */
  __HAL_SPI_DISABLE(&hspi1);                      /* 先禁用SPI*/
  hspi1.Instance->CR1 &= 0xFFC7;                  /* 位 3-5 清零，用来设置波特率 */
  hspi1.Instance->CR1 |= (speed << 3);            /* 设置新的波特率 */
  __HAL_SPI_ENABLE(&hspi1);
}

